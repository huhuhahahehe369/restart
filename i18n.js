function normalizePunctuation(value) {
    return String(value)
        .replace(/\s+([,.!?;:])/g, "$1")
        .replace(/([,.!?])\s*([,.!?])+/g, "$1")
        .replace(/[ \t]{2,}/g, " ")
        .replace(/\s+([·])/g, " $1")
        .trim();
}

function neutralizeEnglish(value) {
    let result = String(value);

    if (Object.prototype.hasOwnProperty.call(neutralEnglishPhrases, result)) {
        return neutralEnglishPhrases[result];
    }

    result = result
        .replace(/\bif you may need it later\b/gi, "if needed later")
        .replace(/\bwhen you close or refresh the app\b/gi, "when the app is closed or refreshed")
        .replace(/\bfor you\b/gi, "")
        .replace(/\byou've earned it\b/gi, "time for a rest")
        .replace(/\byou can\b/gi, "can")
        .replace(/\byou want to\b/gi, "to")
        .replace(/\byou are\b/gi, "")
        .replace(/\byou're\b/gi, "")
        .replace(/\byou've\b/gi, "")
        .replace(/\byou'll\b/gi, "")
        .replace(/\byou'd\b/gi, "")
        .replace(/\byour\b/gi, "")
        .replace(/\byours\b/gi, "")
        .replace(/\byourself\b/gi, "")
        .replace(/\byourselves\b/gi, "")
        .replace(/\byou\b/gi, "");

    return normalizePunctuation(result);
}

function neutralizeVietnamese(value) {
    let result = String(value);

    if (Object.prototype.hasOwnProperty.call(neutralVietnamesePhrases, result)) {
        return neutralVietnamesePhrases[result];
    }

    result = result
        .replace(/\bcủa\s+Cún\b/gi, "")
        .replace(/\bcủa\s+mày\b/gi, "")
        .replace(/\bcủa\s+bạn\b/gi, "")
        .replace(/\bCún\b/gi, "")
        .replace(/\bmày\b/gi, "")
        .replace(/\bbạn\b/gi, "")
        .replace(/\bchính mình\b/gi, "")
        .replace(/\bcho mình\b/gi, "")
        .replace(/\bmình\b/gi, "");

    return normalizePunctuation(result);
}

function containsVietnamese(value) {
    return /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i.test(value);
}

function neutralizeUnknownText(value, language) {
    const original = String(value);

    if (language === "bi" && original.includes(" · ")) {
        return original.split(" · ").map(part =>
            containsVietnamese(part)
                ? neutralizeVietnamese(part)
                : neutralizeEnglish(part)
        ).join(" · ");
    }

    if (containsVietnamese(original)) {
        return neutralizeVietnamese(original);
    }

    return neutralizeEnglish(original);
}

