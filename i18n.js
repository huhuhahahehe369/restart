function getDialogLanguage() {
    try {
        const raw = localStorage.getItem("restart-data-v1");
        const database = raw ? JSON.parse(raw) : null;
        const language = database?.settings?.language;

        return ["en", "vi", "bi"].includes(language) ? language : "en";
    } catch {
        return "en";
    }
}

function neutralizeDialogText(value) {
    const original = String(value ?? "");
    const language = getDialogLanguage();

    if (language === "bi" && original.includes(" · ")) {
        return original.split(" · ").map(part =>
            containsVietnamese(part)
                ? neutralizeVietnamese(part)
                : neutralizeEnglish(part)
        ).join(" · ");
    }

    return containsVietnamese(original)
        ? neutralizeVietnamese(original)
        : neutralizeEnglish(original);
}

function installNeutralDialogCopy() {
    if (typeof window === "undefined" || window.__restartNeutralDialogsInstalled) {
        return;
    }

    const nativeAlert = window.alert.bind(window);
    const nativeConfirm = window.confirm.bind(window);

    window.alert = message => nativeAlert(neutralizeDialogText(message));
    window.confirm = message => nativeConfirm(neutralizeDialogText(message));

    window.__restartNeutralDialogsInstalled = true;
}

