// TRANSLATION ENGINE
// ==========================================

function translateCore(original, language) {
    if (language === "en") {
        return containsVietnamese(original)
            ? neutralizeVietnamese(original)
            : neutralizeEnglish(original);
    }

    const vietnamese =
        translations[original] ||
        translateDynamic(original);

    if (!vietnamese) {
        return neutralizeUnknownText(original, language);
    }

    const neutralVietnamese = neutralizeVietnamese(vietnamese);

    if (language === "vi") {
        return neutralVietnamese;
    }

    const english = neutralizeEnglish(original);

    if (english === neutralVietnamese) {
        return english;
    }

    return `${english} · ${neutralVietnamese}`;
}

// ==========================================
// ORIGINAL TEXT TRACKING
// ==========================================

const textRecords = new WeakMap();
const attributeRecords = new WeakMap();

function splitWhitespace(value) {
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    const end = value.length - trailing.length;
    const core = value.slice(leading.length, end);

    return { leading, core, trailing };
}

function translateTextNode(node, language) {
    const current = node.nodeValue;

    if (!current || !current.trim()) return;

    let record = textRecords.get(node);

    if (!record) {
        record = { original: current, output: current };
        textRecords.set(node, record);
    } else if (current !== record.output) {
        record.original = current;
    }

    const parts = splitWhitespace(record.original);
    const translated = translateCore(parts.core, language);

    const output = parts.leading + translated + parts.trailing;
    record.output = output;

    if (node.nodeValue !== output) {
        node.nodeValue = output;
    }
}

function translateElementAttributes(element, language) {
    const attributes = [
        "placeholder",
        "title",
        "aria-label",
        "alt"
    ];

    let records = attributeRecords.get(element);

    if (!records) {
        records = new Map();
        attributeRecords.set(element, records);
    }

    for (const attribute of attributes) {
        if (!element.hasAttribute(attribute)) continue;

        const current = element.getAttribute(attribute);
        let record = records.get(attribute);

        if (!record) {
            record = { original: current, output: current };
            records.set(attribute, record);
        } else if (current !== record.output) {
            record.original = current;
        }

        const translated = translateCore(record.original, language);
        record.output = translated;

        if (current !== translated) {
            element.setAttribute(attribute, translated);
        }
    }
}

// ==========================================
// APPLY TRANSLATIONS
// ==========================================

export function applyTranslations(language = "en", root = document.body) {
    const safeLanguage = ["en", "vi", "bi"].includes(language)
        ? language
        : "en";

    document.documentElement.lang =
        safeLanguage === "vi" ? "vi" : "en";

    if (!root) return;

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];

    let node;

    while ((node = walker.nextNode())) {
        const parent = node.parentElement;

        if (
            parent &&
            ["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA"].includes(parent.tagName)
        ) {
            continue;
        }

        textNodes.push(node);
    }

    for (const textNode of textNodes) {
        translateTextNode(textNode, safeLanguage);
    }

    const elements = root.querySelectorAll("*");

    for (const element of elements) {
        translateElementAttributes(element, safeLanguage);
    }

    if (root.nodeType === Node.ELEMENT_NODE) {
        translateElementAttributes(root, safeLanguage);
    }
}

// ==========================================
// OBSERVE DYNAMIC CONTENT
// ==========================================

let translationObserver = null;

export function observeTranslations(getLanguage) {
    if (translationObserver) return;

    if (!document.body || typeof MutationObserver === "undefined") {
        return;
    }

    translationObserver = new MutationObserver(mutations => {
        const language = getLanguage();

        for (const mutation of mutations) {
            if (mutation.type === "characterData") {
                translateTextNode(mutation.target, language);
                continue;
            }

            if (mutation.type === "childList") {
                for (const addedNode of mutation.addedNodes) {
                    if (addedNode.nodeType === Node.TEXT_NODE) {
                        translateTextNode(addedNode, language);
                    } else if (addedNode.nodeType === Node.ELEMENT_NODE) {
                        applyTranslations(language, addedNode);
                    }
                }
            }

            if (mutation.type === "attributes") {
                translateElementAttributes(mutation.target, language);
            }
        }
    });

    translationObserver.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: [
            "placeholder",
            "title",
            "aria-label",
            "alt"
        ]
    });
}

