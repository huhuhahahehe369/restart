function translateDynamic(value) {
    let match;

    match = value.match(/^Currently studying (.+)$/);
    if (match) return `Đang học: ${match[1]}`;

    match = value.match(/^Tracking study time for (.+)\.$/);
    if (match) return `Đang tính thời gian học: ${match[1]}`;

    match = value.match(/^Session paused · (.+)$/);
    if (match) return `Đã tạm dừng · ${match[1]}`;

    match = value.match(/^Focus (\d+) min · Break (\d+) min$/);
    if (match) return `Tập trung ${match[1]} phút · Nghỉ ${match[2]} phút`;

    match = value.match(/^Break · (\d+) minutes$/);
    if (match) return `Nghỉ giải lao · ${match[1]} phút`;

    match = value.match(/^Started at (.+) · (.+)$/);
    if (match) return `Bắt đầu lúc ${match[1]} · ${match[2]}`;

    match = value.match(/^Stop whenever you're done\.$/i);
    if (match) return "Dừng bất cứ lúc nào.";

    match = value.match(/^No preset duration · Stop whenever you're done\.$/i);
    if (match) return "Không cần đặt thời gian · Dừng bất cứ lúc nào.";

    match = value.match(/^Keep going for (.+)$/i);
    if (match) return `Tiếp tục trong ${match[1]}`;

    match = value.match(
        /^(\d+) of (\d+) Main Sleep sessions were within 60 minutes of your schedule\.$/
    );
    if (match) {
        return `${match[1]} trên ${match[2]} phiên ngủ chính nằm trong khoảng 60 phút so với lịch mục tiêu.`;
    }

    match = value.match(/^(\d+) of total study time$/);
    if (match) return `${match[1]} trên tổng thời gian học`;

    return null;
}

